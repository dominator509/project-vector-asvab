/// An allowlisted MCP peer with its own scoped grants (REQ-026).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct PeerGrant {
    /// Stable peer identity.
    pub peer_id: String,
    /// Capabilities granted to this peer. Never inherited from another peer.
    pub capabilities: BTreeSet<Capability>,
    /// Filesystem roots this peer may touch, if it holds ScopedFileWrite.
    pub scoped_roots: Vec<String>,
    /// Whether the human has consented to this peer being connected.
    pub user_consented: bool,
}

impl PeerGrant {
    pub fn new(peer_id: &str) -> Self {
        Self {
            peer_id: peer_id.to_string(),
            // Least privilege: a new peer starts with nothing.
            capabilities: BTreeSet::new(),
            scoped_roots: Vec::new(),
            user_consented: false,
        }
    }

    pub fn grant(mut self, capability: Capability) -> Self {
        self.capabilities.insert(capability);
        self
    }

    pub fn with_consent(mut self, consented: bool) -> Self {
        self.user_consented = consented;
        self
    }

    pub fn with_roots(mut self, roots: &[&str]) -> Self {
        self.scoped_roots = roots.iter().map(|r| (*r).to_string()).collect();
        self
    }
}

/// Why a tool call was refused.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum DenialReason {
    /// The peer is not allowlisted at all.
    PeerNotAllowlisted,
    /// The human has not consented to this peer.
    NotConsented,
    /// The named tool does not exist.
    UnknownTool,
    /// The peer lacks the capability the tool requires.
    MissingCapability(Capability),
    /// Arguments exceeded the tool's bound.
    ArgumentsTooLarge,
    /// The requested path is outside the peer's scoped roots.
    PathOutsideScope,
}

impl std::fmt::Display for DenialReason {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            DenialReason::PeerNotAllowlisted => write!(f, "peer is not allowlisted"),
            DenialReason::NotConsented => write!(f, "user consent has not been granted"),
            DenialReason::UnknownTool => write!(f, "unknown tool"),
            DenialReason::MissingCapability(c) => write!(f, "missing capability {c:?}"),
            DenialReason::ArgumentsTooLarge => write!(f, "arguments exceed the tool bound"),
            DenialReason::PathOutsideScope => write!(f, "path is outside the peer's scoped roots"),
        }
    }
}

/// An audit record for every tool call attempt (MCP_CONTRACT.md: "Every tool
/// call gets correlation/audit metadata").
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct AuditRecord {
    pub correlation_id: String,
    pub peer_id: String,
    pub tool: String,
    pub outcome: AuditOutcome,
    /// Trust class of the arguments, recorded so injection attempts are visible.
    pub argument_trust: ContentTrust,
    pub detail: String,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum AuditOutcome {
    Allowed,
    Denied,
}

/// The MCP server's decision surface.
pub struct McpRegistry {
    tools: Vec<ToolDefinition>,
    peers: Vec<PeerGrant>,
    audit: Vec<AuditRecord>,
    next_correlation: u64,
}

/// The result of an authorized call, including its audit record.
#[derive(Debug, Clone, PartialEq)]
pub struct AuthorizedCall {
    pub tool: ToolDefinition,
    pub audit: AuditRecord,
}

impl McpRegistry {
    /// Build a registry. Only allowlisted, consented peers are registered.
    pub fn new(peers: Vec<PeerGrant>) -> Self {
        Self {
            tools: default_tools(),
            peers,
            audit: Vec::new(),
            next_correlation: 1,
        }
    }

    pub fn audit_log(&self) -> &[AuditRecord] {
        &self.audit
    }

    pub fn tools(&self) -> &[ToolDefinition] {
        &self.tools
    }

    fn peer(&self, peer_id: &str) -> Option<&PeerGrant> {
        self.peers.iter().find(|p| p.peer_id == peer_id)
    }

    fn record(
        &mut self,
        peer_id: &str,
        tool: &str,
        outcome: AuditOutcome,
        trust: ContentTrust,
        detail: String,
    ) -> AuditRecord {
        let correlation_id = format!("mcp-{:06}", self.next_correlation);
        self.next_correlation += 1;
        let rec = AuditRecord {
            correlation_id,
            peer_id: peer_id.to_string(),
            tool: tool.to_string(),
            outcome,
            argument_trust: trust,
            detail,
        };
        self.audit.push(rec.clone());
        rec
    }

    /// Authorize a tool call.
    ///
    /// Checks, in order: the peer is allowlisted and consented, the tool exists,
    /// the peer holds the required capability, and the argument size is within
    /// the tool's bound. Every attempt — allowed or denied — is audited, because
    /// an unaudited denial is indistinguishable from a bug.
    pub fn authorize(
        &mut self,
        peer_id: &str,
        tool_name: &str,
        argument_bytes: usize,
        argument_trust: ContentTrust,
    ) -> Result<AuthorizedCall, DenialReason> {
        let peer = match self.peer(peer_id) {
            Some(p) => p.clone(),
            None => {
                self.record(
                    peer_id,
                    tool_name,
                    AuditOutcome::Denied,
                    argument_trust,
                    DenialReason::PeerNotAllowlisted.to_string(),
                );
                return Err(DenialReason::PeerNotAllowlisted);
            }
        };

        if !peer.user_consented {
            self.record(
                peer_id,
                tool_name,
                AuditOutcome::Denied,
                argument_trust,
                DenialReason::NotConsented.to_string(),
            );
            return Err(DenialReason::NotConsented);
        }

        let tool = match self.tools.iter().find(|t| t.name == tool_name) {
            Some(t) => t.clone(),
            None => {
                self.record(
                    peer_id,
                    tool_name,
                    AuditOutcome::Denied,
                    argument_trust,
                    DenialReason::UnknownTool.to_string(),
                );
                return Err(DenialReason::UnknownTool);
            }
        };

        if !peer.capabilities.contains(&tool.required_capability) {
            let reason = DenialReason::MissingCapability(tool.required_capability);
            self.record(
                peer_id,
                tool_name,
                AuditOutcome::Denied,
                argument_trust,
                reason.to_string(),
            );
            return Err(reason);
        }

        if argument_bytes > tool.max_argument_bytes {
            self.record(
                peer_id,
                tool_name,
                AuditOutcome::Denied,
                argument_trust,
                DenialReason::ArgumentsTooLarge.to_string(),
            );
            return Err(DenialReason::ArgumentsTooLarge);
        }

        let audit = self.record(
            peer_id,
            tool_name,
            AuditOutcome::Allowed,
            argument_trust,
            "authorized".to_string(),
        );
        Ok(AuthorizedCall { tool, audit })
    }

    /// Check a filesystem path against the peer's scoped roots.
    ///
    /// MCP_CONTRACT.md: "Filesystem/process/network access is never generic;
    /// tools receive typed arguments and capability-scoped roots." Containment
    /// is decided on normalized path *components*, so neither a textual-prefix
    /// sibling ("/data/drafts-evil") nor a traversal ("/data/drafts/../..")
    /// can pass.
    pub fn check_path(&self, peer_id: &str, requested: &str) -> Result<(), DenialReason> {
        let peer = self.peer(peer_id).ok_or(DenialReason::PeerNotAllowlisted)?;
        if !peer.capabilities.contains(&Capability::ScopedFileWrite) {
            return Err(DenialReason::MissingCapability(Capability::ScopedFileWrite));
        }
        if peer.scoped_roots.is_empty() {
            return Err(DenialReason::PathOutsideScope);
        }

        // A path that still contains `..` after normalization escapes its own
        // root and is refused outright. Refusing rather than resolving is
        // deliberate: lexical resolution cannot account for symlinks, so an
        // escaping path is never safe to accept.
        let normalized = normalize_path(requested);
        if normalized.split('/').any(|seg| seg == "..") {
            return Err(DenialReason::PathOutsideScope);
        }

        for root in &peer.scoped_roots {
            let root_norm = normalize_path(root);
            if root_norm.split('/').any(|seg| seg == "..") {
                // A malformed root grants nothing rather than everything.
                continue;
            }
            if normalized == root_norm {
                return Ok(());
            }
            if normalized
                .strip_prefix(&root_norm)
                .is_some_and(|rest| rest.starts_with('/'))
            {
                return Ok(());
            }
        }
        Err(DenialReason::PathOutsideScope)
    }
}

/// Normalize a path for comparison: backslashes to forward slashes, collapse
/// duplicate separators, drop a trailing separator, and strip `.` segments.
///
/// `..` segments are **preserved** so the caller can detect an escaping path
/// rather than have it silently resolved into something that looks contained.
fn normalize_path(path: &str) -> String {
    let unified = path.replace('\\', "/");
    let mut out = String::new();
    for segment in unified.split('/') {
        match segment {
            "" | "." => continue,
            other => {
                if !out.is_empty() {
                    out.push('/');
                }
                out.push_str(other);
            }
        }
    }
    if unified.starts_with('/') {
        format!("/{out}")
    } else {
        out
    }
}

