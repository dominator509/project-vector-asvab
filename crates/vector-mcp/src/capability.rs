//! MCP capability model and least-privilege tool registry.
//!
//! Requirements: REQ-025 (scoped read-only-default study tools/resources),
//! REQ-026 (allowlisted peers, consent/audit), REQ-027 (untrusted-content
//! authority isolation and prompt-injection defence).
//!
//! Binding sources: `MCP_CONTRACT.md` and `SPEC-005-auth-and-permissions.md`.
//!
//! The central security claim this module enforces is **authority isolation**:
//! content that arrives from a peer, a file, or a model is DATA. It never
//! becomes instruction. Every tool call is checked against an explicit
//! capability grant, and every call produces an audit record.

use std::collections::BTreeSet;

use serde::{Deserialize, Serialize};

/// A capability a caller may hold. Capabilities are additive grants; the
/// absence of a grant is a denial, so a new tool defaults to unreachable.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
pub enum Capability {
    /// Read approved content metadata, evidence records and plan summaries.
    ReadStudyData,
    /// Draft a study artifact. Produces a draft, never publishes.
    CreateDraft,
    /// Request practice-set generation.
    GeneratePracticeSet,
    /// Export a redacted repair bundle.
    ExportRepairBundle,
    /// Invoke an explicitly granted writing-agent workflow.
    InvokeWritingAgent,
    /// Write to a capability-scoped filesystem root.
    ScopedFileWrite,
}

impl Capability {
    /// Whether holding this capability permits a mutation of persistent state.
    ///
    /// Read-only is the default posture (MCP_CONTRACT.md). Destructive or
    /// privacy-sensitive actions require an explicit capability, and this
    /// predicate is what lets the registry refuse to auto-grant one.
    pub fn is_mutating(self) -> bool {
        match self {
            Capability::ReadStudyData => false,
            Capability::CreateDraft
            | Capability::GeneratePracticeSet
            | Capability::ExportRepairBundle
            | Capability::InvokeWritingAgent
            | Capability::ScopedFileWrite => true,
        }
    }
}

/// Where a tool's arguments came from. Used to decide how much the content may
/// be trusted, which is the basis of prompt-injection defence.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum ContentTrust {
    /// Produced by VECTOR itself from validated state.
    Trusted,
    /// Supplied by the local user through the app UI.
    UserProvided,
    /// Retrieved from a documented external source; may be stale or wrong.
    ExternalSource,
    /// Retrieved from an MCP peer; fully untrusted (REQ-026/REQ-027).
    PeerProvided,
    /// Generated by a language model; untrusted and may be adversarially
    /// influenced by anything in its context.
    ModelGenerated,
}

impl ContentTrust {
    /// Whether this content may ever be treated as an instruction.
    ///
    /// Only VECTOR's own validated state qualifies. Everything else is data —
    /// this is the whole point of authority isolation.
    pub fn may_be_instruction(self) -> bool {
        matches!(self, ContentTrust::Trusted)
    }

    /// Whether this content must be quarantined before it reaches a model.
    pub fn requires_isolation(self) -> bool {
        !self.may_be_instruction()
    }
}

/// An MCP tool definition.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ToolDefinition {
    pub name: String,
    pub description: String,
    /// The capability a caller must hold to invoke this tool.
    pub required_capability: Capability,
    /// Maximum permitted argument size in bytes.
    pub max_argument_bytes: usize,
}

